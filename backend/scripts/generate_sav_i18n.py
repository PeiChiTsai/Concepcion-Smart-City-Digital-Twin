"""Generate frontend/src/i18nSav.ts (EN -> ES) from the SAV category CSVs.

Run from the repository root: python backend/scripts/generate_sav_i18n.py
Rows in the EN and ES files must be in the same order.
"""

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "backend" / "data"

en = pd.read_csv(DATA / "sav_categories_EN.csv", skipinitialspace=True)
es = pd.read_csv(DATA / "sav_categories_ES.csv", skipinitialspace=True)

if len(en) != len(es):
    raise SystemExit("EN and ES CSV files must have the same number of rows.")

translations = {}

for column in range(3):
    for english, spanish in zip(
        en.iloc[:, column].str.strip(),
        es.iloc[:, column].str.strip(),
    ):
        previous = translations.setdefault(english, spanish)

        if previous != spanish:
            raise SystemExit(
                f"Conflicting translations for '{english}': "
                f"'{previous}' vs '{spanish}'"
            )

lines = ["// Generated by backend/scripts/generate_sav_i18n.py. Do not edit by hand."]
lines.append("export const savEs: Record<string, string> = {")

for english, spanish in translations.items():
    lines.append(f"  {json.dumps(english, ensure_ascii=False)}: {json.dumps(spanish, ensure_ascii=False)},")

lines.append("}")
lines.append("")
lines.append("export const savDepartments: string[] = [")

for department in en.iloc[:, 2].str.strip().drop_duplicates():
    lines.append(f"  {json.dumps(department, ensure_ascii=False)},")

lines.append("]")

(ROOT / "frontend" / "src" / "i18nSav.ts").write_text(
    "\n".join(lines) + "\n",
    encoding="utf-8",
)

print(f"Wrote {len(translations)} translations.")
